package Inheritance;

public class Student extends Person {

	private String rollNo;
	private int mark;
	
	public String getRollNo() {
		return rollNo;
	}
	
	public void setRollNo(String rollNo) {
		this.rollNo = rollNo;
	}
	
	public int getMark() {
		return mark;
	}
	
	public void setMake(int mark) {
		this.mark = mark;
	}
	
}
